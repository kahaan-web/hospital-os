import { sql } from 'drizzle-orm';
import { boolean, check, date, foreignKey, index, integer, pgTable, primaryKey, text, time, timestamp, unique, uuid } from 'drizzle-orm/pg-core';
import { doctors, locations, tenants } from '../schema';
import { patients } from './foundation';
import { admissions } from './adt';

const id = () => uuid('id').primaryKey().default(sql`gen_random_uuid()`);
const tenantId = () => uuid('tenant_id').notNull().references(() => tenants.id);
const createdAt = () => timestamp('created_at', { withTimezone: true }).notNull().defaultNow();
const updatedAt = () => timestamp('updated_at', { withTimezone: true }).notNull().defaultNow();
const ts = (name: string) => timestamp(name, { withTimezone: true });

export const otSurgeryMaster = pgTable(
  'ot_surgery_master',
  {
    id: id(),
    tenantId: tenantId(),
    name: text('name').notNull(),
    surgeryType: text('surgery_type').notNull(),
    department: text('department').notNull().default(''),
    active: boolean('active').notNull().default(true),
    isSample: boolean('is_sample').notNull().default(false),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    unique('ot_surgery_master_tenant_id_uq').on(t.tenantId, t.id),
    index('ot_surgery_master_tenant_idx').on(t.tenantId, t.surgeryType, t.active),
    check('ot_surgery_master_type_chk', sql`surgery_type in ('major', 'minor')`),
  ],
);

